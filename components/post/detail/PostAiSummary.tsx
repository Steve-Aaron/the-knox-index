import React, { useState } from 'react';
import { Platform, Pressable, StyleSheet, Text, View } from 'react-native';
import { AdminSummaryEditor } from '@/components/dashboard/AdminSummaryEditor';
import { accent, neutral, secondary } from '@/theme/colors';
import { radius, spacing } from '@/theme/spacing';
import { font, type } from '@/theme/typography';

/**
 * PostAiSummary
 * --------------
 * 'AI SUMMARY' block of the post detail. Starts from the stored summary; when
 * there is none, offers to generate one (/api/summarise). Admins can edit it
 * inline.
 *
 * Holds the summary in local state, so give it a `key` of the post id when
 * the same instance can switch posts.
 *
 * One job: show (and fill in) a post's AI summary.
 */
interface Props {
  postId:          string;
  initialSummary?: string;
  isAdmin?:        boolean;
}

export function PostAiSummary({ postId, initialSummary, isAdmin = false }: Props) {
  // Generated summary — starts from the BQ value, can be updated live
  const [summary, setSummary]       = useState<string>(initialSummary ?? '');
  const [generating, setGenerating] = useState(false);
  const [genSource, setGenSource]   = useState<'video' | 'text' | null>(null);

  const generateSummary = async () => {
    setGenerating(true);
    try {
      const res  = await fetch('/api/summarise', {
        method:  'POST',
        headers: { 'Content-Type': 'application/json' },
        body:    JSON.stringify({ postId }),
      });
      const data = await res.json() as { summary?: string; source?: 'video' | 'text'; error?: string };
      if (data.summary) {
        setSummary(data.summary);
        setGenSource(data.source ?? null);
      }
    } catch {
      // Failure is surfaced by the button returning to its idle state —
      // no console output, no error detail leaked to the client.
    } finally {
      setGenerating(false);
    }
  };

  return (
    <View style={styles.section}>
      <View style={styles.header}>
        <Text style={styles.kicker}>AI SUMMARY</Text>
        {genSource ? (
          <View style={styles.sourceTag}>
            <Text style={styles.sourceTagText}>
              {genSource === 'video' ? 'from video' : 'from caption'}
            </Text>
          </View>
        ) : null}
      </View>

      {summary ? (
        <Text style={styles.text}>{summary}</Text>
      ) : generating ? (
        <Text style={styles.empty}>Generating summary…</Text>
      ) : (
        <>
          <Text style={styles.empty}>
            No summary yet for this post.
          </Text>
          <Pressable
            onPress={generateSummary}
            style={({ pressed }) => [
              styles.genBtn,
              pressed && { opacity: 0.7 },
            ]}
          >
            <Text style={styles.genBtnText}>✦  Generated by Knox</Text>
          </Pressable>
        </>
      )}

      {isAdmin ? (
        <AdminSummaryEditor
          postId={postId}
          value={summary}
          onSaved={setSummary}
        />
      ) : null}
    </View>
  );
}

const styles = StyleSheet.create({
  // Most prominent block — fills the height left over by the other sections
  section: {
    flex: 1,
    paddingHorizontal: spacing.xl,
    paddingVertical: spacing.lg,
    gap: spacing.sm,
    backgroundColor: 'rgba(255,255,255,0.025)',
    overflow: 'hidden',
  },
  header: {
    flexDirection: 'row',
    alignItems: 'center',
    gap: spacing.sm,
  },
  kicker: {
    ...type.caption,
    color: neutral.textDim,
    fontSize: 12,
    letterSpacing: 0.8,
  },
  sourceTag: {
    backgroundColor: 'rgba(202,193,228,0.10)',
    borderWidth: 1,
    borderColor: 'rgba(202,193,228,0.35)',
    borderRadius: radius.pill,
    paddingHorizontal: 6,
    paddingVertical: 1,
  },
  sourceTagText: {
    fontFamily: font.ui,
    fontSize: 12,
    color: secondary.lilac,
    textTransform: 'none' as const,
  },
  genBtn: {
    marginTop: spacing.sm,
    alignSelf: 'flex-start',
    borderWidth: 1,
    borderColor: 'rgba(95,100,189,0.45)',
    backgroundColor: 'rgba(95,100,189,0.10)',
    borderRadius: radius.pill,
    paddingHorizontal: spacing.md,
    paddingVertical: spacing.sm,
    ...Platform.select({ web: { cursor: 'pointer' } as any, default: {} }),
  },
  genBtnText: {
    fontFamily: font.bold,
    fontSize: 12,
    color: accent.indigo,
    textTransform: 'none' as const,
  },
  text: {
    fontFamily: font.ui,
    color: neutral.text,
    fontSize: 16,
    lineHeight: 24,
    flex: 1,
  },
  empty: {
    fontFamily: font.ui,
    color: neutral.textDim,
    fontSize: 16,
    lineHeight: 20,
    fontStyle: 'italic',
  },
});
